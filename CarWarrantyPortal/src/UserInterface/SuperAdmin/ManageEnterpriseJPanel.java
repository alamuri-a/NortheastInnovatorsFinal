    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed

    int selectedRow = enterpriseJTable.getSelectedRow();

    if (selectedRow < 0) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please select an enterprise row from the table first!", "Warning", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }

    // 1. Get the Enterprise name from column 0, and Network from column 1
    String entName = (String) enterpriseJTable.getValueAt(selectedRow, 0);
    String netName = (String) enterpriseJTable.getValueAt(selectedRow, 1);

    int dialogResult = javax.swing.JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this Enterprise?", "Warning", javax.swing.JOptionPane.YES_NO_OPTION);
    if (dialogResult == javax.swing.JOptionPane.YES_OPTION) {

        // 2. Loop through your data structure to locate and target the exact matching enterprise
        for (Network network : system.getNetworks()) {
            if (network.getName().equals(netName)) {
                for (Enterprise enterprise : network.getEnterprises().getEnterprises()) {
                    if (enterprise.getName().equals(entName)) {
                        // 3. Call your existing directory deletion routine
                        network.getEnterprises().removeEnterprise(enterprise);
                        break;
                    }
                }
            }
        }

        populateTable();
        javax.swing.JOptionPane.showMessageDialog(this, "Enterprise deleted successfully.");
    }


    }//GEN-LAST:event_btnDeleteActionPerformed

