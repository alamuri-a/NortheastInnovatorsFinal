    private void submitJButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_submitJButtonActionPerformed

        Network network = (Network) networkJComboBox.getSelectedItem();
        Enterprise.Type type = (Enterprise.Type) enterpriseTypeJComboBox.getSelectedItem();

        if (network == null || type == null) {
            JOptionPane.showMessageDialog(null, "Invalid Input!");
            return;
        }

        // 3. Extract and validate custom business name text
    String enterpriseName = nameJTextField.getText().trim();
    if (enterpriseName.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please enter an Enterprise name.");
        return;
    }

    // 4. CALL THE DIRECTORY: This uses the factory method seamlessly
    network.getEnterprises().createEnterprise(enterpriseName, type);

    // 5. Clean up UI elements and sync data onto table
    nameJTextField.setText("");
    populateTable();

    javax.swing.JOptionPane.showMessageDialog(this, "Enterprise added to network successfully!");
    }//GEN-LAST:event_submitJButtonActionPerformed

