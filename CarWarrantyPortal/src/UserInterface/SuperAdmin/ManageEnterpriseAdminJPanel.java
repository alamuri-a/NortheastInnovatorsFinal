    private void submitJButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_submitJButtonActionPerformed
        
        Enterprise enterprise = (Enterprise) enterpriseJComboBox.getSelectedItem();

    if (enterprise == null) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please select an Enterprise.");
        return;
    }

    String username = usernameJTextField.getText().trim();
    String password = String.valueOf(passwordJPasswordField.getPassword()).trim();
    String name = nameJTextField.getText().trim();


    if (username.isEmpty() || password.isEmpty() || name.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "All input fields must be filled!");
        return;
    }

    // FIX 1: Create the matching Person object requested by the structural subsystem
    Business.People.Person person = new Business.People.Person(name);

    // FIX 2: Route Employee creation into the enterprise's explicit AdminOrganization
    Employee employee = enterprise.getAdmins().getEmployees().createEmployee(person);

    // FIX 3: Route User Account creation into the AdminOrganization using your correct system Directory class name (UserDirectory)
    // (Replace 'AdminRole' with your structural Role class instantiation)
    enterprise.getAdmins().getUsers().createUser(employee,username, password, new Admin());

    // 4. Clean text fields and sync view
    usernameJTextField.setText("");
    passwordJPasswordField.setText("");
    nameJTextField.setText("");
    populateTable();

    javax.swing.JOptionPane.showMessageDialog(this, "Enterprise Admin created successfully!");
        
    }//GEN-LAST:event_submitJButtonActionPerformed

