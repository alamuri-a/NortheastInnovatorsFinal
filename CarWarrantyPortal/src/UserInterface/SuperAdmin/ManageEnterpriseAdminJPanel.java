    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
  
  
    int selectedRow = enterpriseJTable.getSelectedRow();

    if (selectedRow < 0) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please select an admin account row from the table first!", "Warning", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }

    // Get keys from columns
    String entName = (String) enterpriseJTable.getValueAt(selectedRow, 0);
    String username = (String) enterpriseJTable.getValueAt(selectedRow, 2);

    int dialogResult = javax.swing.JOptionPane.showConfirmDialog(this, "Delete administrative credentials for " + username + "?", "Warning", javax.swing.JOptionPane.YES_NO_OPTION);
    if (dialogResult == javax.swing.JOptionPane.YES_OPTION) {

        for (Network network : system.getNetworks()) {
            for (Enterprise enterprise : network.getEnterprises().getEnterprises()) {
                if (enterprise.getName().equals(entName)) {

                    // Loop through the explicit AdminOrganization users directory
                    for (User ua : enterprise.getAdmins().getUsers().getUsers()) {
                        if (ua.getUsername().equals(username)) {
                            // Call the deletion routine on the directory
                            enterprise.getAdmins().getUsers().removeUser(ua);
                            break;
                        }
                    }
                }
            }
        }

        populateTable();
        javax.swing.JOptionPane.showMessageDialog(this, "Administrative account removed.");
    }


    }//GEN-LAST:event_btnDeleteActionPerformed

