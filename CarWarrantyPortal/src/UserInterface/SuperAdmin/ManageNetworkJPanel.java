    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
       int selectedRow = networkJTable.getSelectedRow();

    if (selectedRow < 0) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please select a network row from the table first!", "Warning", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }
     Network network = (Network) networkJTable.getValueAt(selectedRow, 0);

    int dialogResult = javax.swing.JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this Network? This will wipe all its enterprises!", "Warning", javax.swing.JOptionPane.YES_NO_OPTION);
    if (dialogResult == javax.swing.JOptionPane.YES_OPTION) {
        system.deleteNetwork(network);
        populateTable();
        javax.swing.JOptionPane.showMessageDialog(this, "Network deleted successfully.");
    }

    }//GEN-LAST:event_btnDeleteActionPerformed

