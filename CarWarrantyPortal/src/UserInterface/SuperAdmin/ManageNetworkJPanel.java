private void populateTable() {
    DefaultTableModel model = (DefaultTableModel) networkJTable.getModel();
    model.setRowCount(0);

    for (Network network : system.getNetworks()) {
        Object[] row = new Object[1]; // Or however many columns your table has

        // FIX: Put the entire object here, NOT network.getName()
        row[0] = network;

        model.addRow(row);
    }
}


