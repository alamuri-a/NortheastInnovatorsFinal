    private void btnCompleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCompleteActionPerformed
        // Add new stock to company database
        
        // Validate if task still needs to be complete
        if (task.isCompleted()) {
            JOptionPane.showMessageDialog(null, "Task has already been completed.", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        // Field validation
        String strQuantity = txtQuantity.getText();
        if (strQuantity.isBlank()) {
            JOptionPane.showMessageDialog(null, "Requested quantity cannot be blank.", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        int quantity = -1;
        try {
            quantity = Integer.parseInt(strQuantity);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Requested quantity must be an integer.", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        // Update in backend
        SupplierEnterprise company = (SupplierEnterprise) organization.getCompany();
        Part part = task.getPart();
        int oldQuantity = company.getPartQuantity(part);
        company.setPartQuantity(part, oldQuantity - quantity);
        
        // Update task status
        organization.getInTasks().popTask(task);
        organization.getOutTasks().pushTask(task);
        ((WarehouseClerk) user.getRole()).completeTask();
        
        // Notify and refresh
        JOptionPane.showMessageDialog(null, "Part successfully removed from stock, please return and track a new task.", "Success", JOptionPane.INFORMATION_MESSAGE);
        refreshFields();
    }//GEN-LAST:event_btnCompleteActionPerformed

    private void btnBackOrderActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBackOrderActionPerformed
        // Create build order for specified part
        
        // Validate if task still needs to be complete
        if (task.isCompleted()) {
            JOptionPane.showMessageDialog(null, "Task has already been completed.", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        BackOrderJPanel bojp = new BackOrderJPanel(workArea, user, organization, business, task);
        this.workArea.add(bojp, "BackOrders");
        ((CardLayout) this.workArea.getLayout()).next(workArea);
    }//GEN-LAST:event_btnBackOrderActionPerformed

    private void btnUnassignActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUnassignActionPerformed
        // Unassign task
        
        if (task.getAssignee() != null) {
            
            // Display confirmation dialog
            int dialogResult = JOptionPane.showConfirmDialog(null,"Are you sure you want to unassign this task?", "Warning", JOptionPane.YES_NO_OPTION);
            if (dialogResult == JOptionPane.YES_OPTION) {
                task.setAssignee(null);
                ((WarehouseClerk) user.getRole()).setCurrentTask(null);
                
                workArea.remove(this);
                ((CardLayout) workArea.getLayout()).previous(workArea);
            }
        }
    }//GEN-LAST:event_btnUnassignActionPerformed


