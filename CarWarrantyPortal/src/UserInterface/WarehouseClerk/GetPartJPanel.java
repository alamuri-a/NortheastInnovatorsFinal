    public void refreshFields() {
        int stock = ((SupplierEnterprise) organization.getCompany()).getPartQuantity(task.getPart());
        int quantity = task.getQuantity();
        
        txtPart.setText(task.getPart().toString());
        txtStock.setText(String.valueOf(stock));
        txtQuantity.setText(String.valueOf(quantity));
        
        if (quantity > stock) btnComplete.setEnabled(false);
        else btnComplete.setEnabled(true);
        
        if (task.isBackordered()) btnBackOrder.setEnabled(false);
        else btnBackOrder.setEnabled(true);
    }
