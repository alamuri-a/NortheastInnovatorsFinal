    private void refreshOrgCombo() {
        // Fill combo with orgs
        DefaultComboBoxModel model = (DefaultComboBoxModel) cmbOrganization.getModel();
        
        model.removeAllElements();
        
        for (Organization org : company.getOrganizations().getOrganizations()) {
            model.addElement(org.getName());
        }
    }

    private void refreshOrgTaskTable(Organization selectedOrg) {
        // Refresh table with selected orgs task breakdown
        DefaultTableModel model = (DefaultTableModel) tblOrganizations.getModel();
        
        model.setRowCount(0);
        
        // Binds # waiting and # completed with Task type
        HashMap<String, ArrayList<Integer>> tasks = new HashMap();
        
        // Tasks waiting
        for (WorkTask task : selectedOrg.getInTasks().getTasks()) {
            
            String className = task.getClass().toString();
            int lastPeriod = className.lastIndexOf('.');
            className = className.substring(lastPeriod+1);
            
            ArrayList<Integer> values = tasks.get(className);
            if (values == null) {
                values = new ArrayList();
                values.add(1);
                values.add(0);
            } else {
                int current = values.get(0);
                values.set(0, current+1);
            }
            
            tasks.put(className, values);
        }
        
        // Tasks completed
        for (WorkTask task : selectedOrg.getOutTasks().getTasks()) {
            
            String className = task.getClass().toString();
            int lastPeriod = className.lastIndexOf('.');
            className = className.substring(lastPeriod+1);
            
            ArrayList<Integer> values = tasks.get(className);
            if (values == null) {
                values = new ArrayList();
                values.add(0);
                values.add(1);
            } else {
                int complete = values.get(1);
                values.set(1, complete+1);
            }
            
            tasks.put(className, values);
        }
        
        // Fill table
        for(String cName : tasks.keySet()) {
            Object[] row = new Object[3];
            
            row[0] = cName;
            row[1] = tasks.get(cName).get(0);
            row[2] = tasks.get(cName).get(1);
            
            model.addRow(row);
        }
    }

    private void refreshUserTaskTable() {
        // Fill table with users + task completion/creation stats
        DefaultTableModel model = (DefaultTableModel) tblUsers.getModel();
        
        model.setRowCount(0);
        
        // All users from company
        HashMap<User, Organization> users = new HashMap();
        for (User u : organization.getUsers().getUsers()) {
            users.put(u, organization);
        }
        for (Organization org : company.getOrganizations().getOrganizations()) {
            for (User u : org.getUsers().getUsers()) {
                users.put(u, org);
            }
        }
        
        // Fill table
        for (User selectedUser : users.keySet()) {
            Organization selectedOrg = users.get(selectedUser);
            
            // Get currently completed tasks
            int completed = 0;
            for (WorkTask task : selectedOrg.getOutTasks().getTasks()) {
                if (task.getAssignee() != null) {
                    if (task.getAssignee().getID() == selectedUser.getID()) completed++;
                }
            }

            Object[] row = new Object[5];

            row[0] = selectedOrg;
            row[1] = selectedUser.toString();
            row[2] = selectedUser.getRole().toString();
            row[3] = selectedOrg instanceof AdminOrganization ? "N/A" : completed;
            row[4] = selectedOrg instanceof AdminOrganization ? "N/A" : selectedUser.getTasksCreated();

            model.addRow(row);
        }
    }
