    private void cmbOrganizationActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cmbOrganizationActionPerformed
        // Fill table with relevant information
        
        // Selection validation
        int selectedIndex = cmbOrganization.getSelectedIndex();
        if (selectedIndex < 0 || selectedIndex > cmbOrganization.getItemCount()) {
            JOptionPane.showMessageDialog(null, "Please select a valid organization.", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        String orgName = (String) cmbOrganization.getItemAt(selectedIndex);
        if (orgName == null || orgName.isBlank()) {
            JOptionPane.showMessageDialog(null, "Organization name is invalid.", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        // Get correct organization
        Organization selectedOrg = null;
        for (Organization org : company.getOrganizations().getOrganizations()) {
            if (org.getName().equals(orgName)) selectedOrg = org;
        }
        if (selectedOrg == null) {
            JOptionPane.showMessageDialog(null, "Failed to find selected organization.", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        // Refresh table with tasks
        refreshOrgTaskTable(selectedOrg);
    }//GEN-LAST:event_cmbOrganizationActionPerformed


