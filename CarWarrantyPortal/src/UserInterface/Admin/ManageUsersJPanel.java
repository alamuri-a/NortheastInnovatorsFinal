    public void refreshTable() {
        // Fill table with necessary info
        DefaultTableModel model = (DefaultTableModel) tblUsers.getModel();
        
        model.setRowCount(0);
        
        for (User u : organization.getUsers().getUsers()) {
            Object[] row = new Object[4];
            
            row[0] = u.getUsername();
            row[1] = u.getRole();
            row[2] = u;
            row[3] = organization;
            
            model.addRow(row);
        }
        
        for (Organization org : organization.getCompany().getOrganizations().getOrganizations()) {
            for (User u : org.getUsers().getUsers()) {
                Object[] row = new Object[4];

                row[0] = u.getUsername();
                row[1] = u.getRole();
                row[2] = u;
                row[3] = org;
                
                model.addRow(row);
            }
        }
    }
