    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // Delete selected user

        // Validate selected organization
        int selectedRow = tblUsers.getSelectedRow();
        if (selectedRow < 0 || selectedRow > tblUsers.getRowCount()) {
            JOptionPane.showMessageDialog(null, "Please select a user from the table first.", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        User selectedUser = (User) tblUsers.getValueAt(selectedRow, 2);
        Organization selectedOrganization = (Organization) tblUsers.getValueAt(selectedRow, 3);
        if (selectedUser == null || selectedOrganization == null) {
            JOptionPane.showMessageDialog(null, "Failed to delete user.", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        } else if (selectedUser.getID() == user.getID()) {
            JOptionPane.showMessageDialog(null, "Cannot delete yourself.", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // Remove in backend
        selectedOrganization.getUsers().removeUser(selectedUser);
        
        // Notify + refresh
        JOptionPane.showMessageDialog(null, "Successfully deleted user!", "Success", JOptionPane.INFORMATION_MESSAGE);
        refreshTable();
    }//GEN-LAST:event_btnDeleteActionPerformed

