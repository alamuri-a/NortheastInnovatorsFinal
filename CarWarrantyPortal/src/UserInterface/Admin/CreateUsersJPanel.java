    private void btnCreateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCreateActionPerformed
        // TODO add your handling code here:
        // Validate organization, employee, username, password, role
        if (selectedOrganization == null) {
            JOptionPane.showMessageDialog(null, "Please select an organization from the left table first.", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (selectedEmployee == null) {
            JOptionPane.showMessageDialog(null, "Please select an employee from the top table first.", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        int selectedIndex = cmbRole.getSelectedIndex();
        if (selectedIndex < 0 || selectedIndex > cmbRole.getItemCount()) {
            JOptionPane.showMessageDialog(null, "Please select a valid role from the combo box first.", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }
        String roleName = cmbRole.getItemAt(selectedIndex);
        if (roleName.isBlank()) {
            JOptionPane.showMessageDialog(null, "Please select a valid role from the combo box first.", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        Role role;
        switch (roleName) {
            case "Admin" -> role = new Admin();
            case "Logistics Coordinator" -> role = new LogisticsCoordinator();
            case "Warehouse Clerk" -> role = new WarehouseClerk();
            case "Sales Representative" -> role = new SalesRepresentative();
            case "Customer Service Representative" -> role = new CustomerServiceRepresentative();
            case "Service Manager" -> role = new ServiceManager();
            case "Service Technician" -> role = new ServiceTechnician();
            case "Production Manager" -> role = new ProductionManager();
            case "Quality Inspector" -> role = new QualityInspector();
            default -> {
                JOptionPane.showMessageDialog(null, "Could not create role for user.", "Warning", JOptionPane.WARNING_MESSAGE);
                return;
            }
        }
        
        String username = txtUsername.getText();
        String password = txtPassword.getText();
        if (username.isBlank() || password.isBlank()) {
            JOptionPane.showMessageDialog(null, "Username/Password cannot be blank.", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        // Update backend
        selectedOrganization.getUsers().createUser(selectedEmployee, username, password, role);
        
        // Notify + refresh
        JOptionPane.showMessageDialog(null, "Successfully created user!", "Success", JOptionPane.INFORMATION_MESSAGE);
        Component[] panelStack = workArea.getComponents();
        JPanel lastPanel = (JPanel) panelStack[panelStack.length - 2];
        ManageUsersJPanel mujp = (ManageUsersJPanel) lastPanel;
        mujp.refreshTable(); // Update table
    }//GEN-LAST:event_btnCreateActionPerformed

    private void tblOrganizationsMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblOrganizationsMouseClicked
        // Validate selected organization
        int selectedRow = tblOrganizations.getSelectedRow();
        if (selectedRow < 0 || selectedRow > tblOrganizations.getRowCount()) {
            JOptionPane.showMessageDialog(null, "Please select an organization from the left table first.", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        Organization selectedOrg = (Organization) tblOrganizations.getValueAt(selectedRow, 0);
        if (selectedOrg == null) {
            JOptionPane.showMessageDialog(null, "Failed to get organization.", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        this.selectedOrganization = selectedOrg;
        
        refreshEmployees();
        refreshCombo();
    }//GEN-LAST:event_tblOrganizationsMouseClicked

