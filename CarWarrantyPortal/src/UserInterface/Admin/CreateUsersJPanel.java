    private void refreshOrganizations() {
        DefaultTableModel model = (DefaultTableModel) tblOrganizations.getModel();
        
        model.setRowCount(0);
        
        Object[] row = new Object[1];
        
        row[0] = organization;
        
        model.addRow(row);
        
        for (Organization o : organization.getCompany().getOrganizations().getOrganizations()) {
            row = new Object[1];
            
            row[0] = o;
            
            model.addRow(row);
        }
    }
    
    private void refreshEmployees() {
        DefaultTableModel model = (DefaultTableModel) tblEmployees.getModel();
        
        model.setRowCount(0);
        
        for (Employee e : selectedOrganization.getEmployees().getEmployees()) {
            Object[] row = new Object[1];
            
            row[0] = e;
            
            model.addRow(row);
        }
    }

    private void refreshCombo() {
        DefaultComboBoxModel model = (DefaultComboBoxModel) cmbRole.getModel();
        
        model.removeAllElements();
        
        cmbRole.setEnabled(false);
        switch (selectedOrganization) {
            case AdminOrganization ao -> model.addElement("Admin");
            case LogisticsOrganization lo -> model.addElement("Logistics Coordinator");
            case WarehousingOrganization wo -> model.addElement("Warehouse Clerk");
            case SalesOrganization sao -> {
                model.addElement("Sales Representative");
                model.addElement("Customer Service Representative");
                cmbRole.setEnabled(true);
            }
            case ServiceOrganization seo -> {
                model.addElement("Service Manager");
                model.addElement("Service Technician");
                cmbRole.setEnabled(true);
            }
            case ProductionOrganization po -> model.addElement("Production Manager");
            case QualityAssuranceOrganization qao -> model.addElement("Quality Inspector");
            case default -> {}
        }
    }
