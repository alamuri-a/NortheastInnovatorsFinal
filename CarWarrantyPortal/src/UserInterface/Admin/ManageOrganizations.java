    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:

        // Validate selected organization
        int selectedRow = tblOrganizations.getSelectedRow();
        if (selectedRow < 0 || selectedRow > tblOrganizations.getRowCount()) {
            JOptionPane.showMessageDialog(null, "Please select an organization from the table first.", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        Organization selectedOrganization = (Organization) tblOrganizations.getValueAt(selectedRow, 1);
        if (selectedOrganization == null) {
            JOptionPane.showMessageDialog(null, "Failed to delete organization.", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        } else if (selectedOrganization instanceof AdminOrganization admins) {
            JOptionPane.showMessageDialog(null, "Cannot delete organization you are currently part of.", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        // Remove in backend
        organization.getCompany().getOrganizations().removeOrganization(selectedOrganization);
        
        refreshTable();
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void btnCreateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCreateActionPerformed
        // TODO add your handling code here:
        
        // Validate organization type + name
        String name = txtName.getText();
        if (name.isBlank()) {
            JOptionPane.showMessageDialog(null, "Organization name cannot be blank.", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        OrganizationDirectory orgs = organization.getCompany().getOrganizations();
        int selectedIndex = cmbOrganization.getSelectedIndex();
        if (selectedIndex < 0 || selectedIndex > cmbOrganization.getItemCount()) {
            JOptionPane.showMessageDialog(null, "Please select an organization type from the combo box.", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        try {
            switch(selectedIndex) {
                case 0 -> orgs.createSalesOrganization(name);
                case 1 -> orgs.createServiceOrganization(name);
                case 2 -> orgs.createLogisticsOrganization(name);
                case 3 -> orgs.createWarehousingOrganization(name);
                case 4 -> orgs.createProductionOrganization(name);
                case 5 -> orgs.createQualityAssuranceOrganization(name);
                default -> {}
            }
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(null, ex.getMessage(), "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        JOptionPane.showMessageDialog(null, "Successfully created organization!", "Success", JOptionPane.INFORMATION_MESSAGE);
        refreshTable();
    }//GEN-LAST:event_btnCreateActionPerformed

