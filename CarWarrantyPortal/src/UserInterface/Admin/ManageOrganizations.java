    public void refreshTable() {
        DefaultTableModel model = (DefaultTableModel) tblOrganizations.getModel();
        
        model.setRowCount(0);
        
        Object[] row = new Object[5];
        row[0] = organization.getID();
        row[1] = organization;
        row[2] = organization.getEmployees().getEmployees().size();
        row[3] = "N/A";
        row[4] = "N/A";
        
        model.addRow(row);
        
        for (Organization o : organization.getCompany().getOrganizations().getOrganizations()) {
            row = new Object[5];
            
            row[0] = o.getID();
            row[1] = o;
            row[2] = o.getEmployees().getEmployees().size();
            row[3] = o.getInTasks().getTasks().size();
            row[4] = o.getOutTasks().getTasks().size();
            
            model.addRow(row);
        }
    }

    private void populateCombo() {
        DefaultComboBoxModel model = (DefaultComboBoxModel) cmbOrganization.getModel();
        
        model.removeAllElements();
        
        model.addElement("Sales");
        model.addElement("Service");
        model.addElement("Logistics");
        model.addElement("Warehouse");
        model.addElement("Production");
        model.addElement("QA");
    }
